/** Short product name: the ERS logo and the browser tab use it. */
export const APP_NAME = 'ERS';

/** The full logo, served from the admin's public folder. */
export const LOGO_URL = '/logo.svg';

/**
 * Browser tab title. Refine builds "Events | Refine" or "#<uuid> Show Sessions | Refine"; the product
 * name replaces "Refine" and the record id (meaningless to a person) is dropped.
 */
export function documentTitle(autoGeneratedTitle: string): string {
  return autoGeneratedTitle.replace(/^#\S+\s+/, '').replace(/Refine$/, APP_NAME);
}
